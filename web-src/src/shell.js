/* ---------------- search palette (Ctrl K / Cmd K) ----------------
   Lists every page in the menu, worthwhile actions (Add Booking, Add Expense, Add Task...), entries pages add through
   PAGES.<id>.search = [{label, icon, run(ctx)}], and when you type: bookings, customers and cars. */
UI.palette = (function () {
  var P = { extra: [] };
  P.register = function (fn) { P.extra.push(fn); };
  function base() {
    var out = [], add = function (g, label, icon, run, hint, kw) { out.push({ group: g, label: label, icon: icon, run: run, hint: hint || '', kw: (label + ' ' + (kw || '')).toLowerCase() }); };
    if (pageAllowed('dashboard')) add('Pages', 'Dashboard', 'layout-dashboard', function () { go('dashboard'); });
    menuGroups().forEach(function (g) { g.items.forEach(function (id) { add(g.label, PAGE_META[id][0], PAGE_META[id][1], function () { go(id); }, '', id === 'invoices' ? 'receipts payments' : ''); }); });
    add('Your account', 'Settings', 'adjustments', function () { go('settings'); }, 'Start page, menu layout, locations');
    if (pageAllowed('website')) add('Your account', 'Website templates', 'world', function () { go('website'); });
    var acts = [['bookings.create', 'Add Booking', 'calendar-plus', function () { API.newBooking(); }], ['expenses.add', 'Add Expense', 'receipt-2', function () { API.addExpense(); }], ['tasks.create', 'Add Task', 'checklist', function () { go('tasks', { action: 'add' }); }],
      ['billing.record_payment', 'Upload payment slip', 'upload', function () { API.uploadSlips(); }], ['billing.record_payment', 'Record payment', 'cash', function () { API.recordPayment(''); }], ['expenses.view', 'Bank in cash', 'building-bank', function () { API.bankIn(); }], ['cars.create', 'New Car', 'car', function () { go('cars', { action: 'add' }); }],
      ['maintenance.create', 'Log a service', 'tool', function () { API.logService(); }], ['summons.add', 'Add summons', 'gavel', function () { go('summons', { action: 'add' }); }], ['users.create', 'Add person', 'user-plus', function () { go('team', { action: 'add' }); }], ['calendar.view', 'Check availability', 'calendar-search', function () { go('availability'); }]];
    acts.forEach(function (a) { if (can(a[0])) add('Actions', a[1], a[2], a[3]); });
    Object.keys(PAGES).forEach(function (id) { var p = PAGES[id]; if (p && p.search && pageAllowed(id)) p.search.forEach(function (s) { add(s.group || PAGE_META[id] && PAGE_META[id][0] || 'More', s.label, s.icon || 'point', function () { go(id); if (s.run) setTimeout(function () { s.run(CUR && CUR.ctx); }, 30); }, s.hint, s.keywords); }); });
    P.extra.forEach(function (f) { (f() || []).forEach(function (s) { add(s.group || 'More', s.label, s.icon || 'point', s.run, s.hint, s.keywords); }); });
    return out;
  }
  function dataHits(q) {
    var d = D(), out = [];
    if (q.length < 2) return out;
    if (can('bookings.view')) d.bookings.filter(function (x) { return (x.code + ' ' + x.cust.name + ' ' + x.car.plate + ' ' + x.cust.phone).toLowerCase().indexOf(q) >= 0; }).slice(-5).reverse().forEach(function (x) { out.push({ group: 'Bookings', label: x.code + ' · ' + x.cust.name, hint: x.car.plate + ' · ' + x.status, icon: 'calendar-event', run: function () { go('bookings', { booking: x.code }); API.openBooking(x.code); } }); });
    if (can('customers.view')) d.people.filter(function (p) { return (p.name + ' ' + p.phone + ' ' + p.email).toLowerCase().indexOf(q) >= 0; }).slice(0, 5).forEach(function (p) { out.push({ group: 'Customers', label: p.name, hint: p.phone, icon: 'user', run: function () { go('customers', { customer: p.id }); API.openCustomer(p.id); } }); });
    if (can('cars.view')) d.cars.filter(function (c) { return (c.plate + ' ' + c.make + ' ' + c.model).toLowerCase().indexOf(q) >= 0; }).slice(0, 5).forEach(function (c) { out.push({ group: 'Cars', label: c.plate + ' · ' + carName(c), icon: 'car', run: function () { go('cars', { car: c.id }); API.openCar(c.id); } }); });
    return out;
  }
  P.open = function () {
    if (document.querySelector('.ui-pal-ov')) return;
    var all = base(), sel = 0, list = [];
    var ov = document.createElement('div'); ov.className = 'ui-ov ui-pal-ov';
    ov.innerHTML = '<div class="ui-pal" role="dialog" aria-modal="true" aria-label="Search"><div class="ui-pal-in">' + i('search') + '<input type="text" placeholder="Search pages, actions, bookings, customers, cars" aria-label="Search" role="combobox" aria-expanded="true" aria-controls="ui-pal-list" autocomplete="off"><button type="button" class="ui-pal-esc" aria-label="Close">Esc</button></div><div class="ui-pal-list" id="ui-pal-list" role="listbox"></div><div class="ui-pal-f"><span><kbd>↑</kbd><kbd>↓</kbd> to navigate</span><span><kbd>Enter</kbd> to open</span><span><kbd>Esc</kbd> to close</span></div></div>';
    document.body.appendChild(ov); document.documentElement.classList.add('ui-locked');
    var inp = ov.querySelector('input'), box = ov.querySelector('.ui-pal-list');
    var close = function () { ov.remove(); if (!UI.top()) document.documentElement.classList.remove('ui-locked'); };
    function draw() {
      var q = inp.value.trim().toLowerCase();
      list = q ? all.filter(function (x) { return x.kw.indexOf(q) >= 0 || x.hint.toLowerCase().indexOf(q) >= 0; }).concat(dataHits(q)) : all.filter(function (x) { return x.group !== 'Your account'; }).slice(0, 40);
      if (sel >= list.length) sel = Math.max(0, list.length - 1);
      var g = null, html = '';
      list.forEach(function (x, k) { if (x.group !== g) { g = x.group; html += '<div class="ui-pal-g" role="presentation">' + esc(g) + '</div>'; } html += '<button type="button" role="option" class="ui-pal-i" data-k="' + k + '" aria-selected="' + (k === sel) + '" id="pal-' + k + '">' + i(x.icon) + '<span class="grow">' + esc(x.label) + '</span>' + (x.hint ? '<small>' + esc(x.hint) + '</small>' : '') + i('corner-down-left', 'ui-pal-enter') + '</button>'; });
      box.innerHTML = list.length ? html : '<div class="ui-pal-none">' + i('mood-empty') + '<b>No result for "' + esc(inp.value) + '"</b><span class="b2">Try a page name, a booking ID, a plate or a phone number.</span></div>';
      inp.setAttribute('aria-activedescendant', list.length ? 'pal-' + sel : '');
      var cur = box.querySelector('[aria-selected="true"]'); if (cur) cur.scrollIntoView({ block: 'nearest' });
    }
    var run = function (k) { var x = list[k]; if (!x) return; close(); x.run(); };
    inp.addEventListener('input', function () { sel = 0; draw(); });
    inp.addEventListener('keydown', function (ev) {
      if (ev.key === 'ArrowDown') { ev.preventDefault(); sel = Math.min(list.length - 1, sel + 1); draw(); }
      else if (ev.key === 'ArrowUp') { ev.preventDefault(); sel = Math.max(0, sel - 1); draw(); }
      else if (ev.key === 'Enter') { ev.preventDefault(); run(sel); }
      else if (ev.key === 'Escape') { ev.preventDefault(); ev.stopPropagation(); close(); }
    });
    ov.addEventListener('click', function (ev) { var x = ev.target.closest('[data-k]'); if (x) run(+x.getAttribute('data-k')); else if (ev.target === ov || ev.target.closest('.ui-pal-esc')) close(); });
    draw(); setTimeout(function () { inp.focus(); }, 20);
  };
  return P;
})();
