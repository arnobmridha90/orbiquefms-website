/* ---------------- the address: #b=0&page=bookings&action=add ---------------- */
function writeHash() {
  try {
    var parts = ['b=' + S.b];
    if (S.sec !== 'dash') parts.push('sec=' + S.sec);
    if (S.sec === 'dash') { parts.push('page=' + S.page); Object.keys(S.params || {}).forEach(function (k) { if (S.params[k] !== '' && S.params[k] != null) parts.push(k + '=' + encodeURIComponent(S.params[k])); }); }
    if (S.sec === 'bf') parts.push('bf=' + S.bf.screen);
    var h = '#' + parts.join('&');
    if (location.hash !== h) history.replaceState(null, '', h);
  } catch (e) { /* the address cannot change inside some viewers; nothing depends on it */ }
}
var HASH_KEYS = ['b', 'sec', 'page', 'bf', 'pf', 'set', 'theme', 'drawer', 'full', 'rail', 'agreed', 'lang', 'user'];
function readHash(h) {
  var params = {};
  (h || '').replace(/^#/, '').split('&').forEach(function (kv) {
    if (!kv) return;
    var p = kv.split('='), k = decodeURIComponent(p[0]), v = decodeURIComponent(p[1] || '');
    if (k === 'b' && BRANDS[+v]) S.b = +v;
    else if (k === 'sec') S.sec = v;
    else if (k === 'page') S.page = v;
    else if (k === 'bf') S.bf.screen = +v;
    else if (k === 'pf') S.pf.tab = v;
    else if (k === 'set') S.set = v;
    else if (k === 'theme') { if (v === 'system') document.documentElement.removeAttribute('data-theme'); else document.documentElement.setAttribute('data-theme', v); }
    else if (k === 'drawer') S.drawer = v.indexOf('car') === 0 ? { kind: 'car', i: +v.slice(3) } : { kind: 'booking', code: v };
    else if (k === 'full') S.ws.full = +v;
    else if (k === 'rail') S.rail = v === '1';
    else if (k === 'agreed') { S.bf.agreed = true; S.bf.licence = true; }
    else if (k === 'lang') S.lang = v;
    else if (k === 'user') S.user[BRANDS[S.b].id] = v;
    else params[k] = v;
  });
  var al = PAGE_ALIASES[S.page]; if (al) { S.page = al[0]; Object.assign(params, al[1] || {}); }
  S.params = params;
}

